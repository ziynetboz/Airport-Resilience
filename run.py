#!/usr/bin/env python3
"""
CLI entry point: run the Airport Resilience ABM with config and optional output.
"""

import argparse
from typing import Optional

import pandas as pd

from config import get_default_config, SimulationConfig
from config.defaults import build_simulation_config
from config.copy_config import copy_simulation_config
from model import AirportABM
from metrics import compute_resilience_metrics
from metrics.otp import compute_otp_metrics
from agents.cancel_reason import CancelReason
from agents.passenger_type import PassengerType
from agents.traveler import TravelerState
from viz import (
    export_time_series,
    export_metrics,
    plot_time_series,
    plot_metrics_summary,
    plot_run_summary,
    plot_resilience_curve,
    plot_kpis,
)


def run_simulation(
    config: SimulationConfig,
) -> tuple[pd.DataFrame, dict, dict]:
    """Run one simulation; return time series, OTP, and IROPS summary."""
    model = AirportABM(config)
    model.run_model()
    otp = compute_otp_metrics(
        model.flights,
        config.otp_on_time_tolerance_steps,
    )
    irops = {
        "airline_irops_cancellations": sum(
            1
            for f in model.flights
            if f.state.name == "CANCELLED"
            and f.cancel_reason == CancelReason.AIRLINE_IROPS
        ),
        "mean_inbound_delay_steps": _mean_inbound_delay(model),
        "gdp_edcts_assigned_total": sum(
            1 for f in model.flights if f.edct_step is not None
        ),
        "preferential_assignments_total": model.gate_allocator.preferential_assignments,
        "common_use_assignments_total": model.gate_allocator.common_use_assignments,
        "remote_stand_assignments_total": model.gate_allocator.remote_stand_assignments,
        "gate_holds_total": model.gate_allocator.gate_holds,
        "connecting_passengers": sum(
            1 for t in model.travelers if t.passenger_type == PassengerType.CONNECTING
        ),
        "misconnects": sum(
            1 for t in model.travelers if t.state == TravelerState.MISCONNECTED
        ),
        "terminal_los_final": model.terminal_los.los_code,
        "terminal_occupancy_ratio_final": model.terminal_los.occupancy_ratio,
    }
    return model.get_time_series(), otp, irops


def _mean_inbound_delay(model) -> float:
    delays = [
        f.inbound_delay_steps
        for f in model.flights
        if f.flight_type.name == "ARRIVAL"
    ]
    return float(sum(delays) / len(delays)) if delays else 0.0


def parse_args():
    parser = argparse.ArgumentParser(
        description="Airport Resilience ABM: behavior under weather shocks"
    )
    parser.add_argument(
        "--config",
        type=str,
        default=None,
        help="Path to JSON config file (overrides other args for model params)",
    )
    parser.add_argument("--steps", type=int, default=150, help="Simulation steps")
    parser.add_argument(
        "--shock-at",
        type=int,
        default=60,
        help="Step at which shock starts",
    )
    parser.add_argument(
        "--shock-duration",
        type=int,
        default=12,
        help="Duration of shock (steps)",
    )
    parser.add_argument("--seed", type=int, default=42, help="Random seed")
    parser.add_argument(
        "--no-shock",
        action="store_true",
        help="Run without shock (baseline)",
    )
    parser.add_argument(
        "--runs",
        type=int,
        default=1,
        help="Number of runs (different seeds)",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Output CSV path for time series",
    )
    parser.add_argument(
        "--metrics",
        type=str,
        default=None,
        help="Output CSV path for resilience metrics",
    )
    parser.add_argument(
        "--no-plot",
        action="store_true",
        help="Do not generate or save plots (plots are generated by default)",
    )
    parser.add_argument(
        "--plot-path",
        type=str,
        default="output/plots",
        help="Directory or path prefix for saved plots (default: output/plots)",
    )
    return parser.parse_args()


def main() -> Optional[pd.DataFrame]:
    args = parse_args()

    if args.config is not None:
        from config.loader import load_simulation_config
        config = load_simulation_config(args.config)
        config = copy_simulation_config(
            config,
            n_steps=args.steps if args.steps != 150 else config.n_steps,
            seed=args.seed if config.seed is None else config.seed,
            shock_at_step=None if args.no_shock else (config.shock_at_step or args.shock_at),
        )
    else:
        model_config = get_default_config()
        shock_at = None if args.no_shock else args.shock_at
        config = build_simulation_config(
            model_config,
            shock_at_step=shock_at,
            shock_duration=args.shock_duration,
            seed=args.seed,
        )
        config = copy_simulation_config(config, n_steps=args.steps)

    shock_at = config.shock_at_step
    shock_end = (
        None
        if shock_at is None
        else (shock_at + config.shock_duration - 1)
    )

    all_dfs = []
    otp_by_run: list[dict] = []
    for i in range(args.runs):
        run_config = copy_simulation_config(
            config,
            seed=(config.seed or args.seed) + i,
        )
        df, otp, irops = run_simulation(run_config)
        df["run"] = i
        all_dfs.append(df)
        merged = {**otp, **irops}
        otp_by_run.append(merged)
        if i == 0:
            print("\nOn-Time Performance (OTP) vs published schedule (run 0):")
            for k, v in otp.items():
                print(f"  {k}: {v}")
            print("\nInbound delay / GDP / IROPS / gates / MCT-LoS (run 0):")
            for k, v in irops.items():
                print(f"  {k}: {v}")

    combined = pd.concat(all_dfs, ignore_index=True)
    metrics_df = None

    if args.output:
        export_time_series(combined, args.output)
        print(f"Time series written to {args.output}")

    if not args.no_shock and shock_at is not None and shock_end is not None:
        metrics_list = []
        for i in range(args.runs):
            run_df = combined[combined["run"] == i]
            m = compute_resilience_metrics(
                run_df,
                shock_start_step=shock_at,
                shock_end_step=shock_end,
            )
            m["run"] = i
            if i < len(otp_by_run):
                m.update(otp_by_run[i])
            metrics_list.append(m)
        metrics_df = pd.DataFrame(metrics_list)
        print("\nResilience metrics (with shock):")
        print(metrics_df.to_string())
        if args.metrics:
            export_metrics(metrics_df, args.metrics)
            print(f"\nMetrics written to {args.metrics}")

    if not args.no_plot:
        try:
            from pathlib import Path
            base = Path(args.plot_path)
            base.mkdir(parents=True, exist_ok=True)
            run_id = 0 if args.runs == 1 else None
            plot_time_series(
                combined,
                path=base / "time_series.png",
                run=run_id,
                shock_start=shock_at,
                shock_end=shock_end,
            )
            print(f"Time-series plot saved to {base / 'time_series.png'}")
            plot_resilience_curve(
                combined,
                path=base / "resilience_curve.png",
                run=run_id,
                shock_start=shock_at,
                shock_end=shock_end,
            )
            print(f"Resilience curve saved to {base / 'resilience_curve.png'}")
            plot_kpis(
                combined,
                path=base / "kpis.png",
                run=run_id,
                shock_start=shock_at,
                shock_end=shock_end,
            )
            print(f"KPIs dashboard saved to {base / 'kpis.png'}")
            if metrics_df is not None and not metrics_df.empty:
                plot_metrics_summary(metrics_df, path=base / "metrics_summary.png")
                print(f"Metrics summary plot saved to {base / 'metrics_summary.png'}")
                plot_run_summary(
                    combined,
                    metrics_df=metrics_df,
                    path=base / "run_summary.png",
                    run=run_id,
                    shock_start=shock_at,
                    shock_end=shock_end,
                )
                print(f"Run summary plot saved to {base / 'run_summary.png'}")
        except ImportError as e:
            if "matplotlib" in str(e).lower():
                print("Skipping plots (matplotlib not installed). Install with: pip install matplotlib")
            else:
                raise

    return combined


if __name__ == "__main__":
    main()
